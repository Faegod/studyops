import { expect, test } from '@playwright/test'

test('pausa por chamado, reabre o contexto após recarga e retoma o cronômetro', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Painel de estudos' })).toBeVisible()
  await expect(page.getByText('Suas sessões aparecerão aqui após o primeiro estudo.')).toBeVisible()

  await page.getByRole('button', { name: '5 min', exact: true }).click()
  await expect(page.getByRole('button', { name: '5 min', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Iniciar sessão', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Contexto da sessão' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Onde eu parei?' }).fill('Localizei CPU e memória.')
  await page.getByRole('textbox', { name: 'Anotações em Markdown' }).fill('# Inventário\n\n- Conferir armazenamento.')
  const material = await page.getByLabel('Material aberto').inputValue()
  expect(material).not.toBe('')
  await expect(page.getByRole('timer')).not.toHaveText('00:00')

  await page.getByRole('button', { name: 'Chamado chegou!' }).click()
  const paused = page.getByRole('dialog', { name: 'Sessão pausada' })
  await expect(paused).toBeVisible()
  await expect(paused.getByRole('textbox', { name: 'Onde eu parei?' })).toHaveValue('Localizei CPU e memória.')
  await paused.getByRole('textbox', { name: 'Onde eu parei?' }).fill('Retomar o inventário pelo armazenamento.')
  await paused.getByRole('button', { name: 'Voltar ao painel' }).click()
  await expect(paused).toBeHidden()

  await page.reload()
  await page.getByRole('button', { name: 'Continuar de onde parei' }).click()
  await expect(page.getByRole('heading', { name: 'Resumo para retomar' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Onde eu parei?' })).toHaveValue('Retomar o inventário pelo armazenamento.')
  await expect(page.getByRole('textbox', { name: 'Anotações em Markdown' })).toHaveValue('# Inventário\n\n- Conferir armazenamento.')
  await expect(page.getByLabel('Material aberto')).toHaveValue(material)
  const elapsed = await page.getByRole('timer').textContent()
  expect(elapsed).not.toBe('00:00')
  await page.getByRole('button', { name: 'Retomar cronômetro' }).click()
  await expect(page.getByRole('timer')).not.toHaveText(elapsed ?? '')
  await page.getByRole('button', { name: 'Finalizar sessão', exact: true }).click()
  const finish = page.getByRole('dialog', { name: 'Finalizar sessão' })
  await expect(finish.getByRole('checkbox')).not.toBeChecked()
  await finish.getByRole('button', { name: 'Finalizar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Painel de estudos' })).toBeVisible()
  await expect(page.getByText('Sessão finalizada e registrada no histórico.')).toBeVisible()
})

test('preserva a sessão de outra aba e recupera um cronômetro ao recarregar a aba proprietária', async ({ context, page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Começar a estudar' }).click()
  await expect(page.getByRole('button', { name: 'Chamado chegou!' })).toBeVisible()
  const secondPage = await context.newPage()
  await secondPage.goto('/')
  await expect(secondPage.getByRole('button', { name: 'Chamado chegou!' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Chamado chegou!' })).toBeVisible()
  await secondPage.close()

  await page.getByRole('textbox', { name: 'Onde eu parei?' }).fill('Continuar pelo diagrama.')
  await expect(page.getByRole('timer')).not.toHaveText('00:00')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Resumo para retomar' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Onde eu parei?' })).toHaveValue('Continuar pelo diagrama.')
  await expect(page.getByRole('timer')).not.toHaveText('00:00')
})

test('reabre a PWA offline com o currículo e o caderno acessíveis', async ({ context, page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Painel de estudos' })).toBeVisible()
  await page.evaluate(() => navigator.serviceWorker.ready.then(() => undefined))
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Painel de estudos' })).toBeVisible()
  await page.getByRole('link', { name: 'Minha Trilha' }).click()
  await expect(page.getByRole('heading', { name: 'Minha Trilha' })).toBeVisible()
  await page.getByRole('link', { name: 'Caderno', exact: true }).click()
  await page.getByRole('button', { name: 'Nova anotação' }).click()
  await page.getByRole('textbox', { name: 'Conteúdo da anotação' }).fill('Escrita offline.')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Caderno', exact: true })).toBeVisible()
  await page.getByRole('complementary', { name: 'Lista de anotações' }).getByRole('button', { name: /Nova anotação/ }).click()
  await expect(page.getByRole('textbox', { name: 'Conteúdo da anotação' })).toHaveValue('Escrita offline.')
})

test('valida arquivos e restaura o backup nos modos mesclar e substituir', async ({ page }) => {
  await page.goto('/#caderno')
  await page.getByRole('button', { name: 'Nova anotação' }).click()
  const editor = page.getByRole('textbox', { name: 'Conteúdo da anotação' })
  await editor.fill('Versão do backup.')

  await page.getByRole('link', { name: 'Configurações' }).click()
  const downloadReady = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar backup' }).click()
  const download = await downloadReady
  const backupPath = await download.path()
  expect(backupPath).toBeTruthy()

  await page.getByRole('link', { name: 'Caderno', exact: true }).click()
  const note = page.getByRole('complementary', { name: 'Lista de anotações' }).getByRole('button', { name: /Nova anotação/ })
  await note.click()
  await editor.fill('Versão mais recente.')

  await page.getByRole('link', { name: 'Configurações' }).click()
  const upload = page.locator('input[type=file]')
  await upload.setInputFiles({ name: 'invalido.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await expect(page.getByRole('alert')).toHaveText('O arquivo não contém JSON válido.')
  await upload.setInputFiles(backupPath!)
  const restore = page.getByRole('dialog', { name: 'Importar backup' })
  await restore.getByRole('button', { name: 'Confirmar importação' }).click()
  await expect(restore).toBeHidden()
  await page.getByRole('link', { name: 'Caderno', exact: true }).click()
  await note.click()
  await expect(editor).toHaveValue('Versão mais recente.')

  await page.getByRole('link', { name: 'Configurações' }).click()
  await upload.setInputFiles(backupPath!)
  await restore.getByRole('combobox').selectOption('replace')
  const confirmation = restore.getByRole('button', { name: 'Confirmar importação' })
  await expect(confirmation).toBeDisabled()
  await restore.getByRole('checkbox').check()
  await confirmation.click()
  await expect(restore).toBeHidden()
  await page.getByRole('link', { name: 'Caderno', exact: true }).click()
  await note.click()
  await expect(editor).toHaveValue('Versão do backup.')
})
